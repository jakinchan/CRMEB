-- +----------------------------------------------------------------------
-- | CRMEB 海外会員対応パッチ: 国際電話番号（E.164）を保存できるようにする
-- +----------------------------------------------------------------------
-- | 適用: mysql -u<user> -p <database> < phone_international.sql
-- | テーブル接頭辞が eb_ 以外の場合は一括置換してください。
-- +----------------------------------------------------------------------
-- | 背景:
-- |   会員の電話番号カラムが中国の携帯番号（11桁）前提の幅しかなく、
-- |   国際形式（+819012345678 など、最大 +15桁 = 16文字）を保存できません。
-- |
-- | 保存形式:
-- |   国番号 86（中国）… 国内表記のまま（例: 13800138000）既存会員との互換維持
-- |   それ以外          … E.164 形式（例: +819012345678）
-- |
-- | 桁数の根拠:
-- |   E.164 は国番号を含めて最大15桁。先頭の「+」を含めて16文字。
-- |   将来の余裕を見て 20 文字（連絡先系は記号込みで 25 文字）に拡張します。
-- |
-- | 安全性:
-- |   すべて既存の幅を「広げる」だけの変更で、データの切り捨ては発生しません。
-- |   NOT NULL・デフォルト値・コメントは既存定義をそのまま維持しています。
-- |   何度実行しても結果は同じです（冪等）。
-- +----------------------------------------------------------------------

SET NAMES utf8mb4;

-- ============================================================
-- 1. 会員本体（phone はログインIDとして使用される）
--    record_phone のデフォルトは既存どおり '0' を維持する
-- ============================================================
ALTER TABLE `eb_user`
  MODIFY COLUMN `phone` VARCHAR(20) NOT NULL DEFAULT '' COMMENT '手机号码',
  MODIFY COLUMN `record_phone` VARCHAR(20) NOT NULL DEFAULT '0' COMMENT '记录临时电话';

-- ============================================================
-- 2. 配送先・注文の連絡先
--    記号入り（03-1234-5678 等）も保存されうるため少し広く取る
-- ============================================================
ALTER TABLE `eb_user_address`
  MODIFY COLUMN `phone` VARCHAR(25) NOT NULL DEFAULT '' COMMENT '收货人电话';

ALTER TABLE `eb_store_order`
  MODIFY COLUMN `user_phone` VARCHAR(25) NOT NULL DEFAULT '' COMMENT '用户电话';

ALTER TABLE `eb_store_integral_order`
  MODIFY COLUMN `user_phone` VARCHAR(25) NOT NULL DEFAULT '' COMMENT '用户电话';

-- ============================================================
-- 3. SMS 送信記録（国際番号の送信ログを保存できるようにする）
-- ============================================================
ALTER TABLE `eb_sms_record`
  MODIFY COLUMN `phone` VARCHAR(20) NOT NULL DEFAULT '' COMMENT '接受短信的手机号';

-- ============================================================
-- 4. 店舗スタッフ（海外店舗の担当者を登録できるようにする）
-- ============================================================
ALTER TABLE `eb_system_store_staff`
  MODIFY COLUMN `phone` VARCHAR(20) NOT NULL DEFAULT '' COMMENT '手机号码';
